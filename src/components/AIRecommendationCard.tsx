import {
  Sparkles,
  CheckCircle2,
  Pencil,
  XCircle,
  Replace,
  ArrowUpCircle,
  FileQuestion,
  ShieldAlert,
  TrendingDown,
} from "lucide-react";
import type { DecisionType, Recommendation } from "@/types";
import { recommendationTypeLabel, recommendationStatusLabel } from "@/lib/labels";
import { currency } from "@/lib/format";
import { Badge } from "./ui/Badge";
import { Button } from "./ui/Button";
import { RiskLevelBadge } from "./RiskLevelBadge";
import { ConfidenceIndicator } from "./ConfidenceIndicator";

interface Props {
  recommendation: Recommendation;
  decided: boolean;
  onSelectAction: (decisionType: DecisionType) => void;
}

const primaryActions: {
  key: DecisionType;
  label: string;
  icon: typeof CheckCircle2;
  variant: "primary" | "outline" | "danger";
}[] = [
  { key: "approved_as_recommended", label: "Accept AI recommendation", icon: CheckCircle2, variant: "primary" },
  { key: "approved_with_edited_limit", label: "Edit suggested limit", icon: Pencil, variant: "outline" },
  { key: "declined", label: "Decline", icon: XCircle, variant: "outline" },
  { key: "overrode_recommendation", label: "Override", icon: Replace, variant: "outline" },
  { key: "escalated", label: "Escalate", icon: ArrowUpCircle, variant: "outline" },
  { key: "requested_more_information", label: "Request info", icon: FileQuestion, variant: "outline" },
];

export function AIRecommendationCard({ recommendation, decided, onSelectAction }: Props) {
  const rec = recommendation;

  return (
    <section className="overflow-hidden rounded-xl border border-brand-200/70 bg-white shadow-card">
      {/* Header band signals this is AI-generated, not a final decision */}
      <div className="flex items-start justify-between gap-4 border-b border-brand-100 bg-gradient-to-b from-brand-50/80 to-white px-5 py-4">
        <div className="flex items-start gap-3">
          <div className="flex h-9 w-9 items-center justify-center rounded-lg bg-brand-600 text-white">
            <Sparkles className="h-4.5 w-4.5" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h2 className="text-sm font-semibold text-slate-900">AI Recommendation</h2>
              <Badge tone="bg-brand-50 text-brand-700 ring-brand-600/20">Suggestion</Badge>
            </div>
            <p className="mt-0.5 text-xs text-slate-500">
              Generated by CreditFlow AI · requires human review
            </p>
          </div>
        </div>
        <Badge tone="bg-slate-100 text-slate-600 ring-slate-500/20">
          {recommendationStatusLabel[rec.status]}
        </Badge>
      </div>

      <div className="space-y-5 px-5 py-5">
        {/* Recommendation headline */}
        <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
          <div>
            <div className="text-[11px] uppercase tracking-wide text-slate-400">
              Recommendation
            </div>
            <div className="mt-1 text-lg font-semibold text-slate-900">
              {recommendationTypeLabel[rec.recommendationType]}
            </div>
            <div className="mt-1 flex items-center gap-3 text-sm text-slate-600">
              <span>Requested {currency(rec.requestedLimit)}</span>
              <span className="text-slate-300">→</span>
              <span className="font-medium text-brand-700">
                Suggested {currency(rec.suggestedLimit)}
              </span>
            </div>
          </div>
          <div className="w-full max-w-[200px]">
            <div className="mb-1.5 flex items-center justify-between">
              <span className="text-[11px] uppercase tracking-wide text-slate-400">
                Confidence
              </span>
              <RiskLevelBadge level={rec.riskLevel} />
            </div>
            <ConfidenceIndicator value={rec.confidence} size="sm" />
          </div>
        </div>

        {/* Reasoning */}
        <div className="rounded-lg bg-slate-50 p-4">
          <div className="mb-1.5 text-xs font-semibold text-slate-500">Reasoning</div>
          <p className="text-sm leading-relaxed text-slate-700">{rec.reasoning}</p>
        </div>

        {/* Supporting signals */}
        <div>
          <div className="mb-2 text-xs font-semibold text-slate-500">Supporting signals</div>
          <ul className="space-y-1.5">
            {rec.supportingSignals.map((s, i) => (
              <li key={i} className="flex items-start gap-2 text-sm text-slate-700">
                <CheckCircle2 className="mt-0.5 h-4 w-4 shrink-0 text-emerald-500" />
                {s}
              </li>
            ))}
          </ul>
        </div>

        {/* Two-sided risk framing */}
        <div className="grid gap-3 sm:grid-cols-2">
          <RiskList
            title="Risks if approved"
            items={rec.riskIfApproved}
            icon={ShieldAlert}
            tone="text-amber-600"
          />
          <RiskList
            title="Risks if declined"
            items={rec.riskIfDeclined}
            icon={TrendingDown}
            tone="text-slate-500"
          />
        </div>

        {/* Required human action callout */}
        <div className="flex items-start gap-3 rounded-lg border border-amber-200 bg-amber-50/70 px-4 py-3">
          <ShieldAlert className="mt-0.5 h-4.5 w-4.5 shrink-0 text-amber-600" />
          <div className="text-sm">
            <span className="font-semibold text-amber-800">Required human action:</span>{" "}
            <span className="text-amber-800">
              {rec.requiredReviewerRole} must review and approve, edit, decline, override,
              or escalate. AI cannot finalize this decision.
            </span>
          </div>
        </div>
      </div>

      {/* Decision controls */}
      <div className="border-t border-slate-100 bg-slate-50/60 px-5 py-4">
        <div className="mb-2 text-xs font-medium text-slate-500">
          {decided ? "Decision recorded. Reopen to change." : "Choose an action"}
        </div>
        <div className="flex flex-wrap gap-2">
          {primaryActions.map((a) => (
            <Button
              key={a.key}
              variant={a.variant}
              size="sm"
              onClick={() => onSelectAction(a.key)}
            >
              <a.icon className="h-3.5 w-3.5" />
              {a.label}
            </Button>
          ))}
        </div>
      </div>
    </section>
  );
}

function RiskList({
  title,
  items,
  icon: Icon,
  tone,
}: {
  title: string;
  items: string[];
  icon: typeof ShieldAlert;
  tone: string;
}) {
  return (
    <div className="rounded-lg border border-slate-100 p-3.5">
      <div className={`mb-2 flex items-center gap-1.5 text-xs font-semibold ${tone}`}>
        <Icon className="h-3.5 w-3.5" />
        {title}
      </div>
      <ul className="space-y-1">
        {items.map((it, i) => (
          <li key={i} className="text-sm leading-snug text-slate-600">
            {it}
          </li>
        ))}
      </ul>
    </div>
  );
}
